import 'syntax_tree.dart';
import 'package:fake_sql/features/data/sql_interpreter/errors.dart';
import '../../entity/export_database.dart';
import 'package:fake_sql/features/data/sql_interpreter/auto_increment.dart';

class InsertIntoStatementNode extends ASTNode {
  final String tableName;
  final List<String> columnNames;
  final List<List<dynamic>> insertValues;

  InsertIntoStatementNode({
    required this.tableName,
    this.columnNames = const [],
    this.insertValues = const [],
  });

  @override
  MyDB invoke(MyDB database) {

    final isContain = database.contain(tableName.toLowerCase());
    if (!isContain.contain) throw MySQLErrorNotFound(tableName);
    final table = database.tables[isContain.index!];

    if (columnNames.isNotEmpty) {
      for (final col in columnNames) {
        table.names.firstWhere(
          (e) => e.name.toLowerCase() == col.toLowerCase(),
          orElse: () => throw MySQLErrorNotFound(col),
        );
      }
    }

    Map<int, Set<MyCellData>> columnsWithUnique = {};
    for (int i = 0; i < table.names.length; i++) {
      if (table.names[i].isUnique || table.names[i].isPrimaryKey) {
        Set<MyCellData> set = {};
        for (int j = 0; j < table.dataset.length; j++) {
          set.add(table.dataset[j][i]);
        }
        columnsWithUnique[i] = set;
      }
    }

    List<List<MyCellData>> newCells = [];

    for (int i = 0; i < insertValues.length; i++) {
      final rowInput = insertValues[i];

      if (columnNames.isNotEmpty) {
        if (columnNames.length != rowInput.length) {
          throw MySQLErrorOutRange(rowInput);
        }
      } else {
        if (rowInput.length != table.names.length) {
          throw MySQLErrorOutRange(rowInput);
        }
      }

      Map<String, dynamic> rowInputMap = {};
      if (columnNames.isEmpty) {
        for (int k = 0; k < rowInput.length; k++) {
          rowInputMap[table.names[k].name.toLowerCase()] = rowInput[k];
        }
      } else {
        for (int k = 0; k < columnNames.length; k++) {
          rowInputMap[columnNames[k].toLowerCase()] = rowInput[k];
        }
      }

      List<MyCellData> rowResult = [];

      for (int j = 0; j < table.names.length; j++) {
        final colSettings = table.names[j];
        final colNameLower = colSettings.name.toLowerCase();
        final hasInput = rowInputMap.containsKey(colNameLower);
        final inputValue = rowInputMap[colNameLower];

        dynamic rawValue;
        bool isAutoGenerated = false;

        if (colSettings.autoIncrement && (!hasInput || inputValue == null)) {
          isAutoGenerated = true;
        } 
        else if (hasInput) {
          rawValue = inputValue;
        } 
        else if (colSettings.defaultValue != null) {
          rawValue = colSettings.defaultValue;
        } 
        else if (colSettings.nullable) {
          rawValue = null;
        } 
        else {
          throw MySQLErrorColumnDoesntHasNull(colSettings.name);
        }

        MyCellData cell;
        if (isAutoGenerated) {
          cell = MyAutoIncrement(null, columnsWithUnique[j] ?? {}).invoke();
        } else {
          cell = MyCellData.factory(colSettings.type, rawValue);
        }

        if (colSettings.isUnique || colSettings.isPrimaryKey) {
          final uniqueSet = columnsWithUnique[j] ?? {};
          if (uniqueSet.contains(cell)) {
            throw MySQLErrorIsUnique('${cell.value}', colSettings.name);
          }
          uniqueSet.add(cell);
          columnsWithUnique[j] = uniqueSet;
        }

        rowResult.add(cell);
      }

      newCells.add(rowResult);
    }

    final updatedDataset = [...table.dataset, ...newCells];
    final updatedTable = table.copyWith(dataset: updatedDataset);
    
    final updatedTables = List.generate(
      database.tables.length,
      (index) => database.tables[index].nameTable.toLowerCase() == updatedTable.nameTable.toLowerCase()
          ? updatedTable
          : database.tables[index],
    );

    return database.copyWith(tables: updatedTables);
  }
}